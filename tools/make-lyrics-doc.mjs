// 从 lyrics.mjs 生成歌词库清单（交付文档）
import fs from 'node:fs'
import { SONGS, LYRICS, LYRIC_STATS } from './lyrics.mjs'

const lines = []
lines.push('# 《庐州月 · 许嵩》主题 —— 动态歌词库')
lines.push('')
lines.push(`**共 ${LYRIC_STATS.songs} 首国风曲目、${LYRIC_STATS.lines} 句歌词**，播放时**纯随机**抽取（每次独立均匀，不连续重复同一条）。`)
lines.push('')
lines.push('## 收录口径')
lines.push('')
lines.push('1. 只收许嵩的**国风（中国风）**作品，**不收情歌**；')
lines.push('2. 只收**许嵩本人作词**的作品；')
lines.push('3. 每句均逐字核对于多个独立来源（含网易云音乐官方歌词接口、百度百科词条、一听／歌词坊／5nd／lrc6／wagequ 等），未作任何改写。')
lines.push('')
lines.push('### 已剔除的情歌')
lines.push('')
lines.push('《你若成风》《有何不可》《素颜》。')
lines.push('')
lines.push('### 已剔除的"非许嵩作词"或"题材不符"曲目')
lines.push('')
lines.push('| 曲目 | 剔除原因 |')
lines.push('| --- | --- |')
lines.push('| 《花满楼》 | 作词海雷、作曲马连智 —— 许嵩仅演唱，非其创作 |')
lines.push('| 《不语》 | 词曲火星电台，且为现代口语题材，无国风意象 |')
lines.push('| 《三潭印月》 | 作者署名存疑，且存在词句不一致的两个流传版本 |')
lines.push('| 《纸上雪》 | 作词**方文山**，非许嵩作词 |')
lines.push('| 《早发白帝城》 | 前四句为李白原诗 |')
lines.push('| 《留香》 | 都市流行题材，无国风意象 |')
lines.push('')
lines.push('### 两处旧库错误修正')
lines.push('')
lines.push('| 旧库写法 | 原文（已修正） |')
lines.push('| --- | --- |')
lines.push('| 桥边红药叹夜夜微凉 | **桥边红药叹夜太漫长**（《庐州月》） |')
lines.push('| 半城烟沙 兵临城下 | **半城烟沙 兵临池下**（《半城烟沙》） |')
lines.push('')
lines.push('## 播放方式')
lines.push('')
lines.push('- **纯随机抽取**：每次从全部 ' + LYRIC_STATS.lines + ' 句中独立均匀抽取，不存在固定顺序；')
lines.push('- 唯一约束：**不连续重复同一条**（否则同一句可能连着出现两次，观感像卡住）；')
lines.push('- 播放节奏：每句停留约 7.6 秒，9.2 秒轮换一句；')
lines.push('- 长句自动缩字号：超过 16 字逐级下调，保证竖排整列不超过视口高度 62%。')
lines.push('')
lines.push('## 曲目一览（共 ' + LYRIC_STATS.songs + ' 首）')
lines.push('')
for (const [i, s] of SONGS.entries()) {
  lines.push(`### ${i + 1}. 《${s.title}》（${s.lines.length} 句）`)
  lines.push('')
  for (const l of s.lines) lines.push(`- ${l}`)
  lines.push('')
}
lines.push('## 轮转顺序（前 24 句）')
lines.push('')
lines.push('| # | 歌词 | 出处 |')
lines.push('| --- | --- | --- |')
LYRICS.slice(0, 24).forEach((x, i) => lines.push(`| ${i + 1} | ${x[0]} | 《${x[1]}》 |`))
lines.push('')
lines.push('> 播放节奏：每句停留约 7.6 秒，9.2 秒轮换一句。全部轮完约 ' +
  Math.round(LYRIC_STATS.lines * 9.2 / 60) + ' 分钟。')
lines.push('')

fs.writeFileSync('交付/歌词库.md', lines.join('\n'), 'utf8')
console.log('交付/歌词库.md 已生成：', LYRIC_STATS.songs, '首 /', LYRIC_STATS.lines, '句')
