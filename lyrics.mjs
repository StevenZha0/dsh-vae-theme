/** 所有收录句子的扁平列表（24 首按曲目轮转交织后展平）。
 *  运行时的抽取方式为**纯随机**：每次独立均匀抽取，与本数组顺序无关；
 *  唯一的约束是不连续重复同一条。 */
export const LYRICS = (() => {
  const out = []
  const max = Math.max(...SONGS.map((s) => s.lines.length))
  for (let i = 0; i < max; i++) {
    for (const s of SONGS) {
      if (s.lines[i]) out.push([s.lines[i], s.title])
    }
  }
  return out
})()

export const LYRIC_STATS = {
  songs: SONGS.length,
  lines: LYRICS.length,
  longest: Math.max(...LYRICS.map((x) => x[0].length)),
}
